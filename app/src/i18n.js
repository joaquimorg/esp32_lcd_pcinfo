  function normalizeLanguage(lang) {
    return STRINGS[lang] ? lang : DEFAULT_LANGUAGE;
  }

  /** Função de tradução para um idioma. */
  function translator(lang) {
    const table = STRINGS[normalizeLanguage(lang)];
    return (key, vars) => {
      let s = table[key] ?? STRINGS.en[key] ?? key;
      if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? String(vars[k]) : m));
      return s;
    };
  }

  /**
   * Nome, descrição e textos das propriedades de um componente no idioma pedido.
   * O manifest tem os textos base (em inglês nos componentes incluídos) e,
   * opcionalmente, traduções em manifest.i18n[lang]:
   *   { name, description, properties: { <key>: { label, optionLabels: { <valor>: texto } } } }
   * Os valores das opções (o que fica guardado) nunca mudam: só o texto mostrado.
   */
  function localizeManifest(m, lang) {
    const tr = (m.i18n && m.i18n[lang]) || {};
    const props = tr.properties || {};
    return {
      ...m,
      name: tr.name || m.name,
      description: tr.description || m.description,
      properties: (m.properties || []).map((p) => {
        const pt = props[p.key] || {};
        return {
          ...p,
          label: pt.label || p.label,
          optionLabels: { ...(p.optionLabels || {}), ...(pt.optionLabels || {}) },
        };
      }),
    };
  }

  /**
   * Erro com mensagem traduzível: message em inglês (logs, testes) e key/vars
   * para quem o mostra ao utilizador no idioma escolhido.
   */
  function appError(key, vars) {
    const err = new Error(translator('en')(key, vars));
    err.key = key;
    err.vars = vars;
    return err;
  }

